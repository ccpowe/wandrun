import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = dirname(require.resolve('pele/package.json'));
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
if (version !== '1.6.0') throw new Error(`Expected Pele 1.6.0, got ${version}`);
const license = readFileSync(join(root, 'LICENSE'), 'utf8');
const script = `/*\n${license}\n*/\n` + readFileSync(require.resolve('pele/global'), 'utf8');
const renderer = readFileSync(join(here, '../src/components/rich-message/mermaid-renderer.js'), 'utf8');
const native = join(here, '../src/components/rich-message/pele-assets.ts');
writeFileSync(native,
  `// Generated from pele@${version} by scripts/generate-pele-assets.mjs. Do not edit.\n` +
  `export const peleScript = ${JSON.stringify(script)};\n` +
  `export const mermaidRendererScript = ${JSON.stringify(renderer)};\n`);
const publicDir = join(here, '../public/pele');
mkdirSync(publicDir, { recursive: true });
writeFileSync(join(publicDir, `pele-${version}.js`), script);
writeFileSync(join(publicDir, `mermaid-renderer-${version}.js`), renderer);
writeFileSync(join(here, '../src/components/rich-message/pele-web-assets.ts'),
  `// Generated by scripts/generate-pele-assets.mjs; Web does not import the native payload.\n` +
  `export const peleWebAssets = { script: '/pele/pele-${version}.js', renderer: '/pele/mermaid-renderer-${version}.js' };\n`);
console.log(`Bundled pele@${version} for native and Web`);
