// Rebuild with `node scripts/generate-katex-assets.mjs` from mobile/. The app
// materializes this bundle once as shared native files; Web serves public files.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = dirname(require.resolve('katex/package.json'));
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
if (version !== '0.19.0') throw new Error(`Expected KaTeX 0.19.0, got ${version}`);
const dist = join(root, 'dist');
const fonts = readdirSync(join(dist, 'fonts')).filter(name => name.endsWith('.woff2')).sort();
let css = readFileSync(join(dist, 'katex.min.css'), 'utf8');
// Keep fonts in the shared CSS so no font file/network access is needed.
css = css.replaceAll(/,url\(fonts\/[^)]*\) format\("(?:woff|truetype)"\)/g, '');
for (const name of fonts) {
  const encoded = readFileSync(join(dist, 'fonts', name)).toString('base64');
  css = css.replaceAll(`fonts/${name}`, `data:font/woff2;base64,${encoded}`);
}
if (/url\((?!data:)/.test(css)) throw new Error('Unexpected KaTeX external CSS asset');
// Preserve the upstream license inside the shipped script, not just the generator.
const license = readFileSync(join(root, 'LICENSE'), 'utf8');
const script = `/*! ${license} */\n` + readFileSync(join(dist, 'katex.min.js'), 'utf8');
if (script.includes('</script')) throw new Error('KaTeX script would end the inline element');
const dest = join(here, '../src/components/rich-message/katex-assets.ts');
writeFileSync(dest,
  `// Generated from katex@${version} (${fonts.length} woff2 fonts) by scripts/generate-katex-assets.mjs. Do not edit.\n` +
  `export const katexStyles = ${JSON.stringify(css)};\n` +
  `export const katexScript = ${JSON.stringify(script)};\n`);
const publicDir = join(here, '../public/katex');
mkdirSync(publicDir, { recursive: true });
writeFileSync(join(publicDir, `katex-${version}.js`), script);
writeFileSync(join(publicDir, `katex-${version}.css`), css);
writeFileSync(join(here, '../src/components/rich-message/katex-web-assets.ts'),
  `// Generated by scripts/generate-katex-assets.mjs; Web does not import the native payload.\n` +
  `export const katexWebAssets = { script: '/katex/katex-${version}.js', styles: '/katex/katex-${version}.css' };\n`);
console.log(`Bundled katex@${version}: ${fonts.length} local woff2 fonts`);
