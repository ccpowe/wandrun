"""Generate the shared UI icon allowlist and static RN imports.

Run from repository root with locked lucide-react-native 1.53.0 installed:
python3 src/wandrun/gateway/generate_ui_icons.py
The canonical export declarations in mobile/node_modules/lucide-react-native/dist/esm/icons/index.mjs
are checked before emitting either artifact. Never reflect over the full runtime icon package.
"""

import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
PACKAGE = ROOT / "mobile/node_modules/lucide-react-native"
ICONS = (
    "activity", "arrow-down", "arrow-left", "arrow-right", "arrow-up", "bell",
    "book-open", "calendar-days", "camera", "chart-no-axes-combined", "check",
    "check-check", "chevron-down", "circle-alert", "circle-check", "clock-3",
    "cloud", "code-xml", "download", "external-link", "file-text", "funnel",
    "globe", "heart", "house", "image", "info", "link", "list", "lock-keyhole",
    "mail", "map-pin", "message-circle",
    "minus", "paperclip", "plus", "search", "settings", "share-2", "shield-check",
    "sparkles", "star", "tag", "thumbs-up", "triangle-alert", "upload", "user",
    "users", "wifi", "x",
)


def main() -> None:
    package = json.loads((PACKAGE / "package.json").read_text())
    if package["version"] != "1.53.0":
        raise RuntimeError("Regenerate only after reviewing a new locked lucide version")
    exports = (PACKAGE / "dist/esm/icons/index.mjs").read_text()
    names = dict(re.findall(r"^export \{ default as ([A-Za-z0-9]+) \} from '\./([a-z0-9-]+)\.mjs';$", exports, re.M))
    if len(names) < 1800:
        raise RuntimeError("Lucide canonical exports could not be read")
    selected = {name: names[name] for name in names if names[name] in ICONS}
    if len(selected) != len(ICONS) or len(set(ICONS)) != len(ICONS):
        raise RuntimeError(f"Missing/duplicate curated names: {set(ICONS) - set(selected.values())}")
    ordered = dict(sorted((slug, symbol) for symbol, slug in selected.items()))
    names_json = json.dumps(list(ordered), ensure_ascii=False, indent=2) + "\n"
    (Path(__file__).with_name("ui_icons.json")).write_text(names_json)
    target = ROOT / "mobile/src/components/rich-message/icons.tsx"
    imports = ", ".join(ordered.values())
    target.write_text(
        "// Generated by src/wandrun/gateway/generate_ui_icons.py from lucide-react-native 1.53.0.\n"
        "// Static named imports keep unlisted icons unreachable to Metro.\n"
        f"import {{ {imports} }} from 'lucide-react-native';\n"
        "\nexport const richIcons = {\n" + "".join(f"  '{slug}': {symbol},\n" for slug, symbol in ordered.items()) +
        "} as const;\nexport type RichIconName = keyof typeof richIcons;\n"
    )


if __name__ == "__main__":
    main()
